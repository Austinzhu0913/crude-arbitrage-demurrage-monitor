from dataclasses import dataclass, field
from typing import Dict, List, Optional
import matplotlib.pyplot as plt
import pandas as pd


@dataclass
class MarketConstruct:
    """Historical benchmark parameters calibrated from representative Bloomberg snapshots (Oct 2026)."""
    # 1. Cargo & Shipping Assumptions (Baltic TD3C: MEG to China VLCC Route)
    cargo_volume_bbls: float = 2_000_000.0        # Standard VLCC parcel volume (~270,000 MT)
    td3c_demurrage_usd_day: float = 57_699.0      # Baseline daily demurrage rate assumption ($/day)[cite: 11]
    allowed_laytime_days: float = 3.0            # 72 running hours contractual laytime (SHINC) post-NOR

    # 2. Logistics & Port Charges ($/bbl)
    base_freight_bbl: float = 2.250               # Baseline freight assumption (TD3C flat-rate proxy)
    port_dues_bbl: float = 0.180                  # Coastal destination port dues, pilotage & harbor dues

    # 3. Trade Finance, Losses & Cargo Administration
    financing_apr: float = 0.055                 # Working capital carrying rate (SOFR + spread: 5.5% APR)
    lc_cost_pct: float = 0.0020                  # Documentary Letter of Credit (DLC) issuance (0.20% flat)
    ocean_loss_pct: float = 0.0020               # Contractual ocean loss allowance (0.20%)
    marine_insurance_pct: float = 0.0003         # Marine cargo transit insurance (0.03%)
    inspection_bbl: float = 0.015                # Independent cargo inspection & assay fee (SGS/Saybolt)

    # 4. Single Source of Truth: ICE Brent Forward Curve Snapshot (CO1 through CO12)[cite: 13]
    curve_months: List[str] = field(default_factory=lambda: [
        'M1\n(26/12)', 'M2\n(27/01)', 'M3\n(27/02)', 'M4\n(27/03)',
        'M5\n(27/04)', 'M6\n(27/05)', 'M7\n(27/06)', 'M8\n(27/07)',
        'M9\n(27/08)', 'M10\n(27/09)', 'M11\n(27/10)', 'M12\n(27/11)'
    ])
    curve_prices: List[float] = field(default_factory=lambda: [
        116.72, 111.70, 107.32, 103.77, 100.86, 98.36,
        96.11, 94.06, 92.21, 90.56, 89.11, 87.85
    ])

    # Dubai Benchmark Spread Snapshot (Oct 23, 2026 terminal close: DBL1 - DBL2)[cite: 10]
    dubai_m1_minus_m2: float = -4.056            # Prompt contango spread snapshot ($/bbl)[cite: 10]

    def __post_init__(self):
        if len(self.curve_months) != len(self.curve_prices):
            raise ValueError("curve_months and curve_prices must have matching lengths.")
        if self.cargo_volume_bbls <= 0:
            raise ValueError("cargo_volume_bbls must be strictly positive.")
        if self.td3c_demurrage_usd_day < 0:
            raise ValueError("td3c_demurrage_usd_day cannot be negative.")

    @property
    def brent_m1(self) -> float:
        return self.curve_prices[0]

    @property
    def brent_m2(self) -> float:
        return self.curve_prices[1]

    @property
    def brent_m12(self) -> float:
        return self.curve_prices[-1]


class CrudeDemurrageModel:
    """Quantitative prototype evaluating modeled delivered-cost build-up and delay sensitivities."""

    def __init__(self, construct: Optional[MarketConstruct] = None):
        self.market = construct if construct is not None else MarketConstruct()

    def compute_demurrage_per_bbl(self, waiting_days: float) -> float:
        """
        Calculates demurrage cost per barrel incurred beyond 72h allowed laytime.
        Commercial Assumption: Assumes valid Notice of Readiness (NOR) tendered upon arrival
        and consecutive port waiting time counts strictly against contractual laytime.
        """
        if waiting_days < 0:
            raise ValueError("waiting_days cannot be negative.")
        billable_days = max(0.0, waiting_days - self.market.allowed_laytime_days)
        return (billable_days * self.market.td3c_demurrage_usd_day) / self.market.cargo_volume_bbls

    def compute_delivered_parity(
        self,
        voyage_days: float,
        waiting_days: float,
        hedged_qp: bool = True
    ) -> Dict[str, float]:
        """
        Computes granular modeled delivered cost components.
        - hedged_qp=True: Baseline assumption excluding incremental calendar-roll stress
          (assumes relevant Quotation Period exposure is adequately managed).
        - hedged_qp=False: Stylized sensitivity stress scenario applying linear backwardation decay.
        """
        if voyage_days < 0 or waiting_days < 0:
            raise ValueError("Voyage and waiting days must be non-negative.")

        fob_price = self.market.brent_m1
        total_days = voyage_days + waiting_days

        # 1. Maritime Logistics & Demurrage
        demurrage_bbl = self.compute_demurrage_per_bbl(waiting_days)
        base_logistics_bbl = self.market.base_freight_bbl + self.market.port_dues_bbl

        # 2. Capital Carry, Loss & Administration
        financing_bbl = fob_price * (self.market.financing_apr / 365.0) * total_days
        lc_bbl = fob_price * self.market.lc_cost_pct
        loss_and_ins_bbl = fob_price * (self.market.ocean_loss_pct + self.market.marine_insurance_pct)
        inspection_bbl = self.market.inspection_bbl

        # 3. Stylized Sensitivity Stress Scenario: Linear Calendar Roll Decay
        billable_delay = max(0.0, waiting_days - self.market.allowed_laytime_days)
        prompt_spread = self.market.brent_m1 - self.market.brent_m2  # Prompt-minus-deferred (+5.02 $/bbl)[cite: 13]
        stress_decay_bbl = 0.0 if hedged_qp else (prompt_spread / 30.0) * billable_delay

        total_landed = (
            fob_price +
            base_logistics_bbl +
            demurrage_bbl +
            financing_bbl +
            lc_bbl +
            loss_and_ins_bbl +
            inspection_bbl +
            stress_decay_bbl
        )

        return {
            "fob_price": fob_price,
            "base_logistics": base_logistics_bbl,
            "demurrage": demurrage_bbl,
            "financing": financing_bbl,
            "lc_cost": lc_bbl,
            "loss_and_insurance": loss_and_ins_bbl,
            "inspection": inspection_bbl,
            "stress_decay": stress_decay_bbl,
            "total_landed": total_landed
        }

    def generate_sensitivity_table(
        self,
        voyage_days: float = 21.0,
        delays: Optional[List[int]] = None
    ) -> pd.DataFrame:
        """Constructs scenario evaluation matrix across discharge delay durations."""
        if delays is None:
            delays = [0, 3, 7, 14, 21, 30]

        rows = []
        for d in delays:
            hedged = self.compute_delivered_parity(voyage_days, d, hedged_qp=True)
            unhedged = self.compute_delivered_parity(voyage_days, d, hedged_qp=False)
            hurdle = hedged["total_landed"] - hedged["fob_price"]
            rows.append({
                "Waiting_Days": d,
                "Demurrage_$/bbl": hedged["demurrage"],
                "Financing_$/bbl": hedged["financing"],
                "Hedged_Landed_Cost": hedged["total_landed"],
                "Incremental_Hurdle": hurdle,
                "Stress_Unhedged_Cost": unhedged["total_landed"]
            })
        return pd.DataFrame(rows)

    def render_desk_monitor(self, output_filename: str = "Crude.png"):
        """Renders 3-tier research monitor dashboard calibrated from historical snapshots."""
        plt.style.use('dark_background')
        fig, axes = plt.subplots(1, 3, figsize=(20, 6.5), facecolor='#0a0a0a')
        plt.subplots_adjust(wspace=0.28, left=0.05, right=0.96, top=0.82, bottom=0.14)

        delays = [0, 3, 7, 14, 21, 30]
        df_sens = self.generate_sensitivity_table(delays=delays)

        # Panel 1: Physical Bottleneck & Demurrage Drag
        ax1 = axes[0]
        ax1.set_facecolor('#121212')
        bars = ax1.bar(
            range(len(delays)), df_sens["Demurrage_$/bbl"],
            color='#ff9900', edgecolor='#e68a00', width=0.52, label='Demurrage Drag ($/bbl)'
        )
        ax1.set_title("PANEL 1: PHYSICAL BOTTLENECK & FREIGHT DRAG\n[Baltic TD3C: MEG-China | VLCC 2.0M bbls]",
                      fontsize=10.5, fontweight='bold', color='#ff9900', pad=12)
        ax1.set_xlabel("Port Waiting Duration Post-NOR (Days)", fontsize=9.5, color='#cccccc')
        ax1.set_ylabel("Incurred Demurrage Cost ($/bbl)", fontsize=9.5, color='#cccccc')
        ax1.set_xticks(range(len(delays)))
        ax1.set_xticklabels([f"{d}d" for d in delays], fontsize=9)
        ax1.grid(True, linestyle='--', alpha=0.15, color='#ffffff')

        for bar, cost in zip(bars, df_sens["Demurrage_$/bbl"]):
            if cost > 0:
                ax1.text(bar.get_x() + bar.get_width() / 2, cost + 0.015, f"${cost:.3f}",
                         ha='center', va='bottom', fontsize=8.5, color='#ffffff')
        ax1.axvline(x=1, color='#00ffff', linestyle=':', linewidth=1.2, label='Allowed Laytime (72h)')
        ax1.legend(loc='upper left', frameon=False, fontsize=8.5)

        # Panel 2: Modeled Delivered Cost Escalation (Hedged Baseline vs. Stress-Test Scenario)
        ax2 = axes[1]
        ax2.set_facecolor('#121212')
        ax2.plot(delays, df_sens["Hedged_Landed_Cost"], marker='o', linewidth=2, color='#00bc8c',
                 label='Modeled Delivered Cost (Hedged Baseline)')
        ax2.plot(delays, df_sens["Stress_Unhedged_Cost"], marker='s', linewidth=2, linestyle='--', color='#e74c3c',
                 label='Unhedged Roll Stress Scenario')
        ax2.fill_between(delays, df_sens["Hedged_Landed_Cost"], df_sens["Stress_Unhedged_Cost"],
                         color='#e74c3c', alpha=0.15, label='Illustrative Roll Stress Band')

        ax2.set_title("PANEL 2: MODELED DELIVERED COST ESCALATION\n[Discharge Delay Inflation on Landed Parity]",
                      fontsize=10.5, fontweight='bold', color='#00bc8c', pad=12)
        ax2.set_xlabel("Discharge Delay Scenario (Days)", fontsize=9.5, color='#cccccc')
        ax2.set_ylabel("Modeled Delivered Cost ($/bbl)", fontsize=9.5, color='#cccccc')
        ax2.grid(True, linestyle='--', alpha=0.15, color='#ffffff')
        ax2.legend(loc='upper left', frameon=False, fontsize=8.5)

        # Panel 3: ICE Brent Generic Forward Curve (Settlement Snapshot)[cite: 13]
        ax3 = axes[2]
        ax3.set_facecolor('#121212')
        x_curve = range(len(self.market.curve_months))

        ax3.plot(x_curve, self.market.curve_prices, marker='s', linewidth=2.2, color='#e74c3c', label='Brent Forward Curve (CO1-CO12)')
        ax3.fill_between(x_curve, self.market.curve_prices, min(self.market.curve_prices) - 5, color='#e74c3c', alpha=0.15, label='Backwardation Structure')

        spread_m1_m12 = self.market.brent_m1 - self.market.brent_m12
        ax3.set_title(f"PANEL 3: BRENT FORWARD CURVE STRUCTURE\n[Backwardation: M1-M12 Spread = +${spread_m1_m12:.2f}/bbl]",
                      fontsize=10.5, fontweight='bold', color='#e74c3c', pad=12)
        ax3.set_xlabel("Contract Delivery Month", fontsize=9.5, color='#cccccc')
        ax3.set_ylabel("Settlement Price ($/bbl)", fontsize=9.5, color='#cccccc')
        ax3.set_xticks(x_curve)
        ax3.set_xticklabels(self.market.curve_months, fontsize=7.5)
